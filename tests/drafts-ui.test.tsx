// @vitest-environment jsdom
import { afterEach, describe, expect, it, vi } from 'vitest'
import { cleanup, fireEvent, render, screen } from '@testing-library/react'
import App from '../src/app/App'
import { clearDrafts, createBackup, DRAFT_KEY, saveDraft } from '../src/features/drafts/storage'

afterEach(() => { cleanup(); localStorage.clear(); vi.restoreAllMocks() })
describe('draft workflow', () => {
  it('saves only on request, restores the message and requires a new review', () => {
    const view = render(<App />)
    fireEvent.change(screen.getByLabelText('YOUR MESSAGE'), { target: { value: 'Meeting 2027-05-20 10:00' } })
    fireEvent.click(screen.getByRole('button', { name: 'Find dates' }))
    fireEvent.click(screen.getByRole('button', { name: 'Confirm event 1' }))
    expect(localStorage.getItem(DRAFT_KEY)).toBeNull()
    fireEvent.click(screen.getByText('Saved drafts on this device'))
    fireEvent.change(screen.getByLabelText('DRAFT NAME'), { target: { value: 'Work' } })
    fireEvent.click(screen.getByRole('button', { name: 'Save current message' }))
    expect(screen.getByText('Draft saved on this browser.')).toBeTruthy()
    const saved = JSON.parse(localStorage.getItem(DRAFT_KEY)!)
    expect(saved.drafts[0].text).toBe('Meeting 2027-05-20 10:00')
    expect(saved.drafts[0]).not.toHaveProperty('events')
    view.unmount()
    render(<App />)
    fireEvent.click(screen.getByText('Saved drafts on this device'))
    fireEvent.click(screen.getByRole('button', { name: 'Load draft Work' }))
    expect((screen.getByLabelText('YOUR MESSAGE') as HTMLTextAreaElement).value).toBe('Meeting 2027-05-20 10:00')
    expect((screen.getByRole('button', { name: 'Export .ics' }) as HTMLButtonElement).disabled).toBe(true)
    fireEvent.click(screen.getByRole('button', { name: 'Find dates' }))
    expect(screen.getByRole('button', { name: 'Confirm event 1' })).toBeTruthy()
  })
  it('keeps existing review when loading is cancelled and deletes only after confirmation', () => {
    vi.spyOn(window, 'confirm').mockReturnValue(false)
    render(<App />)
    fireEvent.change(screen.getByLabelText('YOUR MESSAGE'), { target: { value: 'First 2027-05-20 10:00' } })
    fireEvent.click(screen.getByText('Saved drafts on this device'))
    fireEvent.change(screen.getByLabelText('DRAFT NAME'), { target: { value: 'Work' } })
    fireEvent.click(screen.getByRole('button', { name: 'Save current message' }))
    fireEvent.change(screen.getByLabelText('YOUR MESSAGE'), { target: { value: 'Second 2027-05-21 10:00' } })
    fireEvent.click(screen.getByRole('button', { name: 'Find dates' }))
    fireEvent.click(screen.getByRole('button', { name: 'Confirm event 1' }))
    fireEvent.click(screen.getByRole('button', { name: 'Load draft Work' }))
    expect((screen.getByLabelText('YOUR MESSAGE') as HTMLTextAreaElement).value).toContain('Second')
    expect(screen.getByRole('button', { name: 'Confirmed event 1' })).toBeTruthy()
    fireEvent.click(screen.getByRole('button', { name: 'Delete draft Work' }))
    expect(screen.getByRole('button', { name: 'Load draft Work' })).toBeTruthy()
  })
  it('reports corrupt data without overwriting it', () => {
    localStorage.setItem(DRAFT_KEY, 'broken')
    render(<App />)
    fireEvent.click(screen.getByText('Saved drafts on this device'))
    expect(screen.getByText('Saved drafts are unreadable or use an unsupported version. They were not changed.')).toBeTruthy()
    fireEvent.change(screen.getByLabelText('YOUR MESSAGE'), { target: { value: 'Meeting 2027-05-20' } })
    fireEvent.change(screen.getByLabelText('DRAFT NAME'), { target: { value: 'Work' } })
    fireEvent.click(screen.getByRole('button', { name: 'Save current message' }))
    expect(localStorage.getItem(DRAFT_KEY)).toBe('broken')
  })
  it('restores relative-date settings and permits explicit deletion', () => {
    vi.spyOn(window, 'confirm').mockReturnValue(true)
    const view = render(<App />)
    fireEvent.change(screen.getByLabelText('YOUR MESSAGE'), { target: { value: 'Meeting tomorrow 10:00' } })
    fireEvent.change(screen.getByLabelText('REFERENCE DATE FOR RELATIVE DATES'), { target: { value: '2027-05-20' } })
    fireEvent.change(screen.getByLabelText('REFERENCE TIME ZONE'), { target: { value: 'Asia/Bangkok' } })
    fireEvent.click(screen.getByText('Saved drafts on this device'))
    fireEvent.change(screen.getByLabelText('DRAFT NAME'), { target: { value: 'Relative' } })
    fireEvent.click(screen.getByRole('button', { name: 'Save current message' }))
    view.unmount()
    render(<App />)
    fireEvent.click(screen.getByText('Saved drafts on this device'))
    fireEvent.click(screen.getByRole('button', { name: 'Load draft Relative' }))
    expect((screen.getByLabelText('REFERENCE DATE FOR RELATIVE DATES') as HTMLInputElement).value).toBe('2027-05-20')
    expect((screen.getByLabelText('REFERENCE TIME ZONE') as HTMLInputElement).value).toBe('Asia/Bangkok')
    fireEvent.click(screen.getByRole('button', { name: 'Find dates' }))
    expect((screen.getByLabelText('DATE') as HTMLInputElement).value).toBe('2027-05-21')
    fireEvent.click(screen.getByRole('button', { name: 'Delete draft Relative' }))
    expect(screen.queryByRole('button', { name: 'Load draft Relative' })).toBeNull()
  })
  it('imports a backup and still requires a fresh review before calendar export', async () => {
    saveDraft(localStorage, 'Backup', { text: 'Meeting 2027-05-20 10:00', referenceDate: '', referenceZone: 'UTC' })
    const backup = createBackup(localStorage)
    clearDrafts(localStorage)
    const file = new File([backup], 'backup.json', { type: 'application/json' })
    Object.defineProperty(file, 'text', { value: async () => backup })
    render(<App />)
    fireEvent.click(screen.getByText('Saved drafts on this device'))
    fireEvent.click(screen.getByText('Back up or import drafts'))
    fireEvent.change(screen.getByLabelText('SELECT BACKUP JSON'), { target: { files: [file] } })
    await screen.findByText('Backup')
    fireEvent.click(screen.getByRole('button', { name: 'Import these drafts' }))
    fireEvent.click(screen.getByRole('button', { name: 'Load draft Backup' }))
    expect((screen.getByRole('button', { name: 'Export .ics' }) as HTMLButtonElement).disabled).toBe(true)
    fireEvent.click(screen.getByRole('button', { name: 'Find dates' }))
    expect(screen.getByRole('button', { name: 'Confirm event 1' })).toBeTruthy()
  })
})
