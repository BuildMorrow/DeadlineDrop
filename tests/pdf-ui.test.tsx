// @vitest-environment jsdom
import { afterEach, describe, expect, it, vi } from 'vitest'
import { cleanup, fireEvent, render, screen, waitFor } from '@testing-library/react'
import { PdfToText } from '../src/features/pdf/PdfToText'
import { readPdf } from '../src/features/pdf/readPdf'

vi.mock('../src/features/pdf/readPdf', () => ({ readPdf: vi.fn() }))
afterEach(() => { cleanup(); vi.clearAllMocks() })
const sample = () => new File(['%PDF-1.4'], 'sample.pdf', { type: 'application/pdf' })
describe('PDF review controls', () => {
  it('requires review and explicit transfer, and warns about empty pages', async () => {
    vi.mocked(readPdf).mockResolvedValueOnce({ text: 'Deadline 2027-05-20', pages: ['Deadline 2027-05-20', ''] })
    const useText = vi.fn()
    render(<PdfToText onUseText={useText} />)
    fireEvent.click(screen.getByText('Read text from a PDF'))
    fireEvent.change(screen.getByLabelText('PDF (MAX 8 MB, 20 PAGES)'), { target: { files: [sample()] } })
    fireEvent.click(screen.getByRole('button', { name: 'Read PDF' }))
    const result = await screen.findByLabelText('PDF TEXT')
    expect(screen.getByRole('status').textContent).toContain('Some pages')
    expect(screen.getByText('Page 2')).toBeTruthy()
    expect(screen.getByText('No selectable text on this page.')).toBeTruthy()
    expect(useText).not.toHaveBeenCalled()
    fireEvent.change(result, { target: { value: 'Corrected 2027-05-21' } })
    fireEvent.click(screen.getByRole('button', { name: 'Use this text' }))
    expect(useText).toHaveBeenCalledWith('Corrected 2027-05-21')
  })
  it('discards a late result after cancel and restores focus', async () => {
    let complete!: (value: { text: string; pages: string[] }) => void
    vi.mocked(readPdf).mockImplementationOnce(() => new Promise(resolve => { complete = resolve }))
    render(<PdfToText onUseText={vi.fn()} />)
    fireEvent.click(screen.getByText('Read text from a PDF'))
    fireEvent.change(screen.getByLabelText('PDF (MAX 8 MB, 20 PAGES)'), { target: { files: [sample()] } })
    fireEvent.click(screen.getByRole('button', { name: 'Read PDF' }))
    await waitFor(() => expect(readPdf).toHaveBeenCalled())
    const cancel = screen.getByRole('button', { name: 'Cancel' }); cancel.focus(); fireEvent.click(cancel)
    complete({ text: 'stale', pages: ['stale'] })
    await waitFor(() => expect(screen.getByRole('status').textContent).toBe('PDF reading cancelled.'))
    expect(screen.queryByLabelText('PDF TEXT')).toBeNull()
    expect(document.activeElement).toBe(screen.getByRole('button', { name: 'Read PDF' }))
  })
  it('reports invalid or encrypted files without using any text', async () => {
    vi.mocked(readPdf).mockRejectedValueOnce(new Error('password required'))
    const useText = vi.fn(); render(<PdfToText onUseText={useText} />)
    fireEvent.click(screen.getByText('Read text from a PDF'))
    fireEvent.change(screen.getByLabelText('PDF (MAX 8 MB, 20 PAGES)'), { target: { files: [sample()] } })
    fireEvent.click(screen.getByRole('button', { name: 'Read PDF' }))
    await waitFor(() => expect(screen.getByRole('status').textContent).toContain('encrypted'))
    expect(useText).not.toHaveBeenCalled()
  })
  it('shows each empty page without allowing empty text to be transferred', async () => {
    vi.mocked(readPdf).mockResolvedValueOnce({ text: '', pages: ['', ''] })
    render(<PdfToText onUseText={vi.fn()} />)
    fireEvent.click(screen.getByText('Read text from a PDF'))
    fireEvent.change(screen.getByLabelText('PDF (MAX 8 MB, 20 PAGES)'), { target: { files: [sample()] } })
    fireEvent.click(screen.getByRole('button', { name: 'Read PDF' }))
    await screen.findByText('Page 2')
    expect(screen.getAllByText('No selectable text on this page.')).toHaveLength(2)
    expect(screen.queryByRole('button', { name: 'Use this text' })).toBeNull()
  })
  it('rebuilds only selected pages on explicit request and replaces edits', async () => {
    vi.mocked(readPdf).mockResolvedValueOnce({ text: 'First 2027-05-20\n\nSecond 2027-05-21', pages: ['First 2027-05-20', 'Second 2027-05-21', ''] })
    const useText = vi.fn()
    render(<PdfToText onUseText={useText} />)
    fireEvent.click(screen.getByText('Read text from a PDF'))
    fireEvent.change(screen.getByLabelText('PDF (MAX 8 MB, 20 PAGES)'), { target: { files: [sample()] } })
    fireEvent.click(screen.getByRole('button', { name: 'Read PDF' }))
    const input = await screen.findByLabelText('PDF TEXT') as HTMLTextAreaElement
    fireEvent.click(screen.getByText('Review original extracted text by page'))
    expect((screen.getByRole('checkbox', { name: 'Page 3' }) as HTMLInputElement).disabled).toBe(true)
    fireEvent.change(input, { target: { value: 'Personal edits' } })
    fireEvent.click(screen.getByRole('checkbox', { name: 'Page 1' }))
    expect(input.value).toBe('Personal edits')
    fireEvent.click(screen.getByRole('button', { name: 'Rebuild text from selected pages' }))
    expect(input.value).toBe('Second 2027-05-21')
    fireEvent.click(screen.getByRole('button', { name: 'Use this text' }))
    expect(useText).toHaveBeenCalledWith('Second 2027-05-21')
  })
})
