// @vitest-environment jsdom
import { afterEach, describe, expect, it, vi } from 'vitest'
import { cleanup, fireEvent, render, screen, waitFor, within } from '@testing-library/react'
import axe from 'axe-core'
import ICAL from 'ical.js'
import App from '../src/app/App'

afterEach(() => { cleanup(); vi.unstubAllGlobals(); vi.restoreAllMocks() })

describe('event review interaction', () => {
  it('requests a browser warning before leaving with text and removes it when cleared', () => {
    render(<App />)
    const before = new Event('beforeunload', { cancelable: true })
    expect(window.dispatchEvent(before)).toBe(true)
    fireEvent.change(screen.getByLabelText('YOUR MESSAGE'), { target: { value: 'Private draft' } })
    const dirty = new Event('beforeunload', { cancelable: true })
    expect(window.dispatchEvent(dirty)).toBe(false)
    fireEvent.change(screen.getByLabelText('YOUR MESSAGE'), { target: { value: '' } })
    const cleared = new Event('beforeunload', { cancelable: true })
    expect(window.dispatchEvent(cleared)).toBe(true)
  })
  it('reveals relative date settings when needed and keeps source text collapsible', () => {
    render(<App />)
    const settings = screen.getByText('Relative date settings').closest('details')!
    expect(settings.open).toBe(false)
    fireEvent.change(screen.getByLabelText('YOUR MESSAGE'), { target: { value: 'Meeting tomorrow 10:00' } })
    expect(settings.open).toBe(true)
    fireEvent.change(screen.getByLabelText('REFERENCE DATE FOR RELATIVE DATES'), { target: { value: '2027-05-20' } })
    fireEvent.click(screen.getByRole('button', { name: 'Find dates' }))
    const original = screen.getByText('Original text').closest('details')!
    expect(original.open).toBe(false)
    expect(within(original).getByText('Meeting tomorrow 10:00')).toBeTruthy()
    fireEvent.click(screen.getByText('Original text'))
    expect(original.open).toBe(true)
  })
  it('requires confirmation again when the checklist changes', () => {
    render(<App />)
    fireEvent.change(screen.getByLabelText('YOUR MESSAGE'), { target: { value: 'Meeting 2027-05-20 10:00' } })
    fireEvent.click(screen.getByRole('button', { name: 'Find dates' }))
    fireEvent.click(screen.getByRole('button', { name: 'Confirm event 1' }))
    expect((screen.getByRole('button', { name: 'Export .ics' }) as HTMLButtonElement).disabled).toBe(false)
    fireEvent.change(screen.getByLabelText('CHECKLIST (OPTIONAL, ONE ITEM PER LINE)'), { target: { value: 'Bring notes' } })
    expect((screen.getByRole('button', { name: 'Export .ics' }) as HTMLButtonElement).disabled).toBe(true)
    fireEvent.click(screen.getByRole('button', { name: 'Confirm event 1' }))
    expect((screen.getByRole('button', { name: 'Export .ics' }) as HTMLButtonElement).disabled).toBe(false)
  })
  it('allows checklist progress to be changed and requires renewed confirmation', () => {
    render(<App />)
    fireEvent.change(screen.getByLabelText('YOUR MESSAGE'), { target: { value: 'Meeting 2027-05-20 10:00' } })
    fireEvent.click(screen.getByRole('button', { name: 'Find dates' }))
    const input = screen.getByLabelText('CHECKLIST (OPTIONAL, ONE ITEM PER LINE)') as HTMLTextAreaElement
    fireEvent.change(input, { target: { value: 'Bring notes\n\nSend report' } })
    fireEvent.click(screen.getByRole('button', { name: 'Confirm event 1' }))
    fireEvent.click(screen.getByRole('checkbox', { name: 'Send report' }))
    expect(input.value).toBe('Bring notes\n\n- [x] Send report')
    expect((screen.getByRole('button', { name: 'Export .ics' }) as HTMLButtonElement).disabled).toBe(true)
    fireEvent.click(screen.getByRole('checkbox', { name: 'Send report' }))
    expect(input.value).toBe('Bring notes\n\n- [ ] Send report')
  })
  it('has no automated accessibility violations in the initial and ambiguous review states', async () => {
    const { container } = render(<App />)
    const options = { rules: { 'color-contrast': { enabled: false } } }
    expect((await axe.run(container, options)).violations).toEqual([])
    fireEvent.change(screen.getByLabelText('YOUR MESSAGE'), { target: { value: 'Workshop 2027-05-20 10:00-11:00' } })
    fireEvent.click(screen.getByRole('button', { name: 'Find dates' }))
    expect((await axe.run(container, options)).violations).toEqual([])
  })

  it('explains why an invalid title cannot be confirmed', () => {
    render(<App />)
    fireEvent.change(screen.getByLabelText('YOUR MESSAGE'), { target: { value: 'Meeting 2027-05-20 10:00' } })
    fireEvent.click(screen.getByRole('button', { name: 'Find dates' }))
    const title = screen.getByLabelText('EVENT TITLE')
    fireEvent.change(title, { target: { value: 'Meeting\u0001' } })
    expect(title.getAttribute('aria-invalid')).toBe('true')
    expect(document.getElementById(title.getAttribute('aria-describedby')!)?.textContent).toContain('control characters')
    expect((screen.getByRole('button', { name: 'Confirm event 1' }) as HTMLButtonElement).disabled).toBe(true)
  })

  it('exports only confirmed events together through the download action', async () => {
    const originalCreate = Object.getOwnPropertyDescriptor(URL, 'createObjectURL')
    const originalRevoke = Object.getOwnPropertyDescriptor(URL, 'revokeObjectURL')
    const create = vi.fn(() => 'blob:test')
    Object.defineProperty(URL, 'createObjectURL', { configurable: true, value: create })
    Object.defineProperty(URL, 'revokeObjectURL', { configurable: true, value: vi.fn() })
    const click = vi.spyOn(HTMLAnchorElement.prototype, 'click').mockImplementation(() => {})
    try {
      render(<App />)
      fireEvent.change(screen.getByLabelText('YOUR MESSAGE'), { target: { value: 'One 2027-05-20 10:00\nTwo 2027-05-21 11:00\nUncertain 03/04/2027' } })
      fireEvent.click(screen.getByRole('button', { name: 'Find dates' }))
      fireEvent.click(screen.getByRole('button', { name: 'Confirm event 1' }))
      fireEvent.click(screen.getByRole('button', { name: 'Confirm event 2' }))
      expect((screen.getByRole('button', { name: 'Confirm event 3' }) as HTMLButtonElement).disabled).toBe(true)
      vi.useFakeTimers()
      fireEvent.click(screen.getByRole('button', { name: 'Export .ics' }))
      vi.runAllTimers()
      vi.useRealTimers()
      expect(create).toHaveBeenCalledOnce()
      expect(click).toHaveBeenCalledOnce()
      const blob = create.mock.calls[0][0] as unknown as Blob
      const data = await new Promise<string>((resolve, reject) => {
        const reader = new FileReader()
        reader.onload = () => resolve(String(reader.result))
        reader.onerror = () => reject(reader.error)
        reader.readAsText(blob)
      })
      const calendar = new ICAL.Component(ICAL.parse(data))
      expect(calendar.getAllSubcomponents('vevent').map(event => event.getFirstPropertyValue('summary'))).toEqual(['One 2027-05-20 10:00', 'Two 2027-05-21 11:00'])
    } finally {
      vi.useRealTimers()
      click.mockRestore()
      if (originalCreate) Object.defineProperty(URL, 'createObjectURL', originalCreate)
      else Reflect.deleteProperty(URL, 'createObjectURL')
      if (originalRevoke) Object.defineProperty(URL, 'revokeObjectURL', originalRevoke)
      else Reflect.deleteProperty(URL, 'revokeObjectURL')
    }
  })

  it('switches to Vietnamese, translates ambiguity warnings, and preserves the review', () => {
    const { container } = render(<App />)
    fireEvent.change(screen.getByLabelText('YOUR MESSAGE'), { target: { value: 'Meeting 03/04/2027 10:00' } })
    fireEvent.click(screen.getByRole('button', { name: 'Find dates' }))
    fireEvent.change(screen.getByLabelText('Language / Ngôn ngữ'), { target: { value: 'vi' } })
    expect(container.querySelector('.app-shell')?.getAttribute('lang')).toBe('vi')
    expect(screen.getByText('Ngày dạng số có nhiều cách hiểu: hãy chọn đúng ngày.')).toBeTruthy()
    expect((screen.getByRole('button', { name: 'Xác nhận sự kiện 1' }) as HTMLButtonElement).disabled).toBe(true)
    expect((screen.getByLabelText('NỘI DUNG') as HTMLTextAreaElement).value).toBe('Meeting 03/04/2027 10:00')
    fireEvent.click(screen.getByText('Đọc chữ từ ảnh'))
    expect(screen.getByRole('button', { name: 'Đọc ảnh' })).toBeTruthy()
    fireEvent.change(screen.getByLabelText('Language / Ngôn ngữ'), { target: { value: 'en' } })
    expect(screen.getByText('Ambiguous numeric date: choose the correct date.')).toBeTruthy()
  })

  it('switches themes without losing the current review', () => {
    const { container } = render(<App />)
    fireEvent.change(screen.getByLabelText('YOUR MESSAGE'), { target: { value: 'Meeting 2027-05-20 10:00' } })
    fireEvent.click(screen.getByRole('button', { name: 'Find dates' }))
    fireEvent.click(screen.getByRole('button', { name: 'Confirm event 1' }))
    fireEvent.click(screen.getByRole('button', { name: 'Switch to light theme' }))
    expect(container.querySelector('.app-shell')?.getAttribute('data-theme')).toBe('light')
    expect(screen.getByText('1 confirmed event')).toBeTruthy()
    fireEvent.click(screen.getByRole('button', { name: 'Switch to dark theme' }))
    expect(container.querySelector('.app-shell')?.getAttribute('data-theme')).toBe('dark')
  })

  it('announces an offline state without discarding input', () => {
    render(<App />)
    fireEvent.change(screen.getByLabelText('YOUR MESSAGE'), { target: { value: 'Meeting 2027-05-20 10:00' } })
    fireEvent(window, new Event('offline'))
    expect(screen.getByText(/browser reports you are offline/)).toBeTruthy()
    expect((screen.getByLabelText('YOUR MESSAGE') as HTMLTextAreaElement).value).toBe('Meeting 2027-05-20 10:00')
    fireEvent(window, new Event('online'))
    expect(screen.queryByText(/browser reports you are offline/)).toBeNull()
  })

  it('keeps focus in the review after removing events and labels each event group', () => {
    render(<App />)
    fireEvent.change(screen.getByLabelText('YOUR MESSAGE'), { target: { value: 'One 2027-05-20 10:00\nTwo 2027-05-21 11:00' } })
    fireEvent.click(screen.getByRole('button', { name: 'Find dates' }))
    expect(screen.getByRole('article', { name: 'Event 1' })).toBeTruthy()
    const first = screen.getByRole('button', { name: 'Remove event 1' })
    first.focus(); fireEvent.click(first)
    expect(document.activeElement).toBe(screen.getByRole('button', { name: 'Remove event 1' }))
    expect(screen.getByText('1 event found. 0 confirmed.').getAttribute('role')).toBe('status')
    fireEvent.click(screen.getByRole('button', { name: 'Remove event 1' }))
    expect(document.activeElement).toBe(screen.getByRole('heading', { name: 'Review your events' }))
    expect(screen.getByText('0 events found. 0 confirmed.').getAttribute('role')).toBe('status')
  })
  it('associates date and time fields with uncertainty warnings', () => {
    render(<App />)
    fireEvent.change(screen.getByLabelText('YOUR MESSAGE'), { target: { value: 'Meeting 03/04/2027 10:00' } })
    fireEvent.click(screen.getByRole('button', { name: 'Find dates' }))
    const description = screen.getByLabelText('DATE').getAttribute('aria-describedby')
    expect(description).toBeTruthy()
    expect(document.getElementById(description!)?.textContent).toContain('Ambiguous numeric date')
    expect(screen.getByLabelText('TIME').getAttribute('aria-describedby')).toBe(description)
  })

  it('requires a reference date and clears confirmed events if it changes', () => {
    vi.spyOn(window, 'confirm').mockReturnValue(true)
    render(<App />)
    fireEvent.change(screen.getByLabelText('YOUR MESSAGE'), { target: { value: 'Submit tomorrow at 5 pm' } })
    fireEvent.click(screen.getByRole('button', { name: 'Find dates' }))
    expect(screen.getByRole('alert').textContent).toContain('Choose a reference date')
    fireEvent.change(screen.getByLabelText('REFERENCE DATE FOR RELATIVE DATES'), { target: { value: '2027-12-31' } })
    fireEvent.click(screen.getByRole('button', { name: 'Find dates' }))
    expect((screen.getByLabelText('DATE') as HTMLInputElement).value).toBe('2028-01-01')
    expect(screen.getByText(/Relative date based on 2027-12-31/)).toBeTruthy()
    fireEvent.click(screen.getByRole('button', { name: 'Confirm event 1' }))
    expect((screen.getByRole('button', { name: 'Export .ics' }) as HTMLButtonElement).disabled).toBe(false)
    fireEvent.change(screen.getByLabelText('REFERENCE DATE FOR RELATIVE DATES'), { target: { value: '2028-01-01' } })
    expect((screen.getByRole('button', { name: 'Export .ics' }) as HTMLButtonElement).disabled).toBe(true)
    expect(screen.queryByLabelText('DATE')).toBeNull()
  })

  it('clears a confirmed relative event when the reference timezone changes', () => {
    vi.spyOn(window, 'confirm').mockReturnValue(true)
    render(<App />)
    fireEvent.change(screen.getByLabelText('YOUR MESSAGE'), { target: { value: 'Submit tomorrow at 5 pm' } })
    fireEvent.change(screen.getByLabelText('REFERENCE DATE FOR RELATIVE DATES'), { target: { value: '2027-05-20' } })
    fireEvent.click(screen.getByRole('button', { name: 'Find dates' }))
    fireEvent.click(screen.getByRole('button', { name: 'Confirm event 1' }))
    expect((screen.getByRole('button', { name: 'Export .ics' }) as HTMLButtonElement).disabled).toBe(false)
    const zone = screen.getByLabelText('REFERENCE TIME ZONE') as HTMLInputElement
    fireEvent.change(zone, { target: { value: zone.value === 'UTC' ? 'Asia/Bangkok' : 'UTC' } })
    expect((screen.getByRole('button', { name: 'Export .ics' }) as HTMLButtonElement).disabled).toBe(true)
    expect(screen.queryByLabelText('DATE')).toBeNull()
  })

  it('rejects an invalid reference timezone and blocks an ambiguous weekday', () => {
    render(<App />)
    fireEvent.change(screen.getByLabelText('YOUR MESSAGE'), { target: { value: 'Meet next Monday at 09:00' } })
    fireEvent.change(screen.getByLabelText('REFERENCE DATE FOR RELATIVE DATES'), { target: { value: '2027-11-07' } })
    fireEvent.change(screen.getByLabelText('REFERENCE TIME ZONE'), { target: { value: 'Not/A_Zone' } })
    fireEvent.click(screen.getByRole('button', { name: 'Find dates' }))
    expect(screen.getByRole('alert').textContent).toContain('valid IANA')
    fireEvent.change(screen.getByLabelText('REFERENCE TIME ZONE'), { target: { value: 'UTC' } })
    fireEvent.click(screen.getByRole('button', { name: 'Find dates' }))
    expect((screen.getByLabelText('DATE') as HTMLInputElement).value).toBe('')
    expect((screen.getByRole('button', { name: 'Confirm event 1' }) as HTMLButtonElement).disabled).toBe(true)
    expect((screen.getByRole('button', { name: 'Export .ics' }) as HTMLButtonElement).disabled).toBe(true)
  })

  it.runIf(Intl.DateTimeFormat().resolvedOptions().timeZone !== 'America/New_York')('requires selecting a source-zone DST occurrence before confirmation', () => {
    render(<App />)
    fireEvent.change(screen.getByLabelText('YOUR MESSAGE'), { target: { value: 'Tomorrow at 01:30' } })
    fireEvent.change(screen.getByLabelText('REFERENCE DATE FOR RELATIVE DATES'), { target: { value: '2027-11-06' } })
    fireEvent.change(screen.getByLabelText('REFERENCE TIME ZONE'), { target: { value: 'America/New_York' } })
    fireEvent.click(screen.getByRole('button', { name: 'Find dates' }))
    expect((screen.getByRole('button', { name: 'Confirm event 1' }) as HTMLButtonElement).disabled).toBe(true)
    expect((screen.getByLabelText('SOURCE TIME') as HTMLInputElement).disabled).toBe(true)
    expect(screen.queryByText(/^Start:/)).toBeNull()
    fireEvent.click(screen.getByRole('button', { name: 'Second occurrence (UTC-05:00)' }))
    expect((screen.getByRole('button', { name: 'Confirm event 1' }) as HTMLButtonElement).disabled).toBe(false)
  })

  it('allows correcting an ambiguous weekday as an all-day event', () => {
    render(<App />)
    fireEvent.change(screen.getByLabelText('YOUR MESSAGE'), { target: { value: 'Submit next Monday' } })
    fireEvent.change(screen.getByLabelText('REFERENCE DATE FOR RELATIVE DATES'), { target: { value: '2027-05-20' } })
    fireEvent.click(screen.getByRole('button', { name: 'Find dates' }))
    fireEvent.change(screen.getByLabelText('DATE'), { target: { value: '2027-05-24' } })
    fireEvent.click(screen.getByLabelText('All-day event'))
    fireEvent.click(screen.getByRole('button', { name: 'Apply corrected all-day date' }))
    expect((screen.getByRole('button', { name: 'Confirm event 1' }) as HTMLButtonElement).disabled).toBe(false)
  })

  it('moves focus to confirmation after resolving a time range', async () => {
    vi.stubGlobal('requestAnimationFrame', (callback: FrameRequestCallback) => setTimeout(() => callback(0), 0))
    render(<App />)
    expect(screen.getByText(/Calendar apps may add a duration when no end time is provided/)).toBeTruthy()
    fireEvent.change(screen.getByLabelText('YOUR MESSAGE'), { target: { value: 'Workshop 2027-05-20 10:00-11:00' } })
    fireEvent.click(screen.getByRole('button', { name: 'Find dates' }))
    const confirm = screen.getByRole('button', { name: 'Confirm event 1' }) as HTMLButtonElement
    expect(confirm.disabled).toBe(true)
    const resolution = screen.getByRole('group', { name: 'Resolve time ambiguity' })
    fireEvent.click(within(resolution).getByRole('button', { name: 'Use as a time range' }))
    await waitFor(() => expect(document.activeElement).toBe(confirm))
    expect(confirm.disabled).toBe(false)
    fireEvent.click(confirm)
    expect(document.activeElement).toBe(confirm)
    expect(confirm.getAttribute('aria-disabled')).toBe('true')
    fireEvent.click(confirm)
    expect(screen.getByText('1 confirmed event')).toBeTruthy()
    expect((screen.getByRole('button', { name: 'Export .ics' }) as HTMLButtonElement).disabled).toBe(false)
    fireEvent.change(screen.getByLabelText('EVENT TITLE'), { target: { value: 'Updated workshop' } })
    expect((screen.getByRole('button', { name: 'Export .ics' }) as HTMLButtonElement).disabled).toBe(true)
  })
})
