export function translate(language: Language, text: string): string {
  if (language === 'en') return text
  const relative = text.match(/^Relative date based on (.+) in (.+): check the original message\.$/)
  if (relative) return `Ngày tương đối dựa trên ${relative[1]} tại ${relative[2]}: hãy kiểm tra nội dung gốc.`
  return vietnamese[text] ?? text
}
